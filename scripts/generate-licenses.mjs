import fs from 'node:fs';
import path from 'node:path';

const lock = JSON.parse(fs.readFileSync('package-lock.json', 'utf8'));
const sections = ['Third-party notices for the installed dependency tree.\nGenerated by npm run licenses. Dependencies retain their own licenses.\n'];
for (const [directory, entry] of Object.entries(lock.packages).sort(([a], [b]) => a.localeCompare(b))) {
  if (!directory || !fs.existsSync(directory)) continue;
  const pkg = JSON.parse(fs.readFileSync(path.join(directory, 'package.json'), 'utf8'));
  const files = fs.readdirSync(directory).filter((file) => /^(licen[cs]e|copying|notice|third-party-license)(\.|$)/i.test(file)
    && fs.statSync(path.join(directory, file)).isFile());
  sections.push(`\n${'='.repeat(72)}\n${pkg.name}@${entry.version} — ${entry.license || pkg.license}\n${entry.resolved || ''}\n`);
  if (files.length) {
    for (const file of files) sections.push(`\n${file}\n${fs.readFileSync(path.join(directory, file), 'utf8')}\n`);
  } else if (pkg.name.startsWith('@rolldown/binding-')) {
    sections.push('License and third-party notices from the matching rolldown package:\n');
    for (const file of ['LICENSE', 'THIRD-PARTY-LICENSE']) sections.push(fs.readFileSync(`node_modules/rolldown/${file}`, 'utf8'));
  } else if (pkg.name === 'murmurhash-js') {
    const readme = fs.readFileSync(path.join(directory, 'README.md'), 'utf8');
    sections.push(readme.slice(readme.indexOf('## License (MIT)')));
  } else if (pkg.name === 'worker-f' && pkg.license === 'MIT') {
    sections.push('Upstream declares MIT in package.json but ships no separate license or copyright notice.\n');
    sections.push(`Author: ${pkg.author}\nRepository: ${pkg.repository.url}\n`);
    sections.push('Standard MIT permission and disclaimer (not an upstream license file):\n\n');
    const mit = fs.readFileSync('LICENSE', 'utf8');
    sections.push(mit.slice(mit.indexOf('Permission is hereby granted')));
  } else {
    throw new Error(`Missing license text for ${pkg.name}; review before distributing.`);
  }
}
fs.writeFileSync('THIRD_PARTY_LICENSES.txt', sections.join(''));
